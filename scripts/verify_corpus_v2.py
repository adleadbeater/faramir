"""Independently verify data/corpus.v2.json against data/corpus.json and the audit.

Offline; no network or credentials. Writes a Markdown validation report.
Exit code 0 only if every check passes.

Usage:
    python scripts/verify_corpus_v2.py [--out docs/v2/increment1_review/VALIDATION.md]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import subprocess
import sys
from datetime import date

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from faramir.corpus import load_corpus_v2  # noqa: E402
from faramir.corpus_validate import coverage, validate_corpus  # noqa: E402

ADDED_FIELDS = {"identity_status", "identity_source", "identity_checked_at", "domestic_status", "worldwide_status"}
GROSS_FIELDS = {"domestic_lifetime", "worldwide_lifetime"}
REPAIRED_FIELDS = {"tmdb_id", "title", "release_date", "release_year", "genres", "director", "lead_cast",
                   "collection_id", "collection_name", "origin_country", "distributor", "is_classic"}


def sha256(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "v2", "increment1_review", "VALIDATION.md"))
    ap.add_argument("--base-commit", default="f2a0ce4")
    args = ap.parse_args(argv)

    v1_path = os.path.join(ROOT, "data", "corpus.json")
    v2_path = os.path.join(ROOT, "data", "corpus.v2.json")
    audit_path = os.path.join(ROOT, "docs", "v2", "corpus_identity_audit_2026-10-22.csv")
    with open(v1_path) as f:
        v1 = json.load(f)
    with open(v2_path) as f:
        v2 = json.load(f)
    films = v2["films"]
    with open(audit_path, newline="", encoding="utf-8") as f:
        audit = {r["imdb_id"]: int(r["verified_tmdb_id"]) for r in csv.DictReader(f)}

    checks: list[tuple[str, bool, str]] = []

    def check(name, ok, detail=""):
        checks.append((name, bool(ok), detail))

    base_v1 = subprocess.run(["git", "-C", ROOT, "diff", "--quiet", args.base_commit, "--", "data/corpus.json"]).returncode == 0
    check("data/corpus.json unchanged since base commit", base_v1, args.base_commit)
    check("v2 schema version is 2", v2["meta"].get("corpus_schema_version") == 2)
    violations = validate_corpus(v2)
    check("all integrity gates pass", not violations, "; ".join(f"{v.code}: {v.detail}" for v in violations))
    check("same row count as v1", len(films) == len(v1), f"{len(films)} vs {len(v1)}")
    check("same row order (imdb_id) as v1", [f["imdb_id"] for f in films] == [f["imdb_id"] for f in v1])

    gross_ok = all(n[g] == (o[g] or None) for o, n in zip(v1, films) for g in GROSS_FIELDS)
    check("grosses unchanged (0 → None only)", gross_ok)
    check("no confirmed_zero values", not any(f[f"{m}_status"] == "confirmed_zero" for f in films for m in ("domestic", "worldwide")))
    status_ok = all((f[f"{m}_status"] == "reported") == (f[f"{m}_lifetime"] is not None) for f in films for m in ("domestic", "worldwide"))
    check("status matches value on every row", status_ok)

    changed = {n["imdb_id"]: n["tmdb_id"] for o, n in zip(v1, films) if o["tmdb_id"] != n["tmdb_id"]}
    check("relabelled identities == audit CSV (imdb_id → verified tmdb_id)", changed == audit, f"{len(changed)} changed, audit {len(audit)}")
    check("no unresolved identities", all(f["identity_status"] == "verified" for f in films))

    untouched_ok = True
    for o, n in zip(v1, films):
        allowed = ADDED_FIELDS | GROSS_FIELDS | (REPAIRED_FIELDS if n["imdb_id"] in audit else set())
        diff = {k for k in set(o) | set(n) if o.get(k) != n.get(k)} - allowed
        if diff:
            untouched_ok = False
            break
    check("only repaired rows changed metadata; nothing else changed", untouched_ok)
    check("meta.coverage equals recomputed coverage", v2["meta"]["coverage"] == coverage(films))
    load = load_corpus_v2(v2_path, date(2026, 10, 23))
    check("daily loader classifies it OK", load.status == "OK", f"{load.status} {load.reasons}")

    cov = v2["meta"]["coverage"]
    passed = all(ok for _, ok, _ in checks)
    lines = [
        "# Increment 1 repaired-corpus validation",
        "",
        f"Generated by `scripts/verify_corpus_v2.py` (offline). Overall: **{'PASS' if passed else 'FAIL'}**",
        "",
        f"- `data/corpus.json` sha256 `{sha256(v1_path)}`",
        f"- `data/corpus.v2.json` sha256 `{sha256(v2_path)}`",
        f"- gross_as_of {v2['meta']['gross_as_of']}; repaired {v2['meta']['identity_repaired_at']} via {v2['meta']['identity_source']}",
        f"- Coverage: domestic {cov['domestic']['reported']} reported / {cov['domestic']['missing']} missing "
        f"({cov['domestic']['reported_share']:.1%}); worldwide {cov['worldwide']['reported']} / {cov['worldwide']['missing']} "
        f"({cov['worldwide']['reported_share']:.1%})",
        "",
        "| Check | Result | Detail |",
        "|---|---|---|",
    ]
    lines += [f"| {name} | {'PASS' if ok else '**FAIL**'} | {detail} |" for name, ok, detail in checks]
    lines += [
        "",
        "Reproduce: `python scripts/verify_corpus_v2.py`. The Increment 1 code diff is in "
        "`increment1_code.patch` (excludes the two large data files) and the repair build report in "
        "`../corpus_repair_2026-10-23/`.",
        "",
    ]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(("PASS" if passed else "FAIL"), args.out)
    for name, ok, detail in checks:
        if not ok:
            print("FAIL:", name, detail)
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
